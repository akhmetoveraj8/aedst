// Renders the pages of the component reference (docs/content/ui-kit/components) from a manifest
// entry and the per-platform extraction results. Pure functions: no file access here.
import { normalise } from './enums.mjs';
import { firstSentence, pascal } from './source.mjs';

export const PAGES_DIR = 'docs/content/ui-kit/components';
export const ROUTE = '/ui-kit/components';
export const HEADER = '{/* GENERATED by `task docs:ui-kit` (scripts/ui-kit/component-docs.mjs) from ui-kit.yaml and the kit sources. Do not edit by hand. */}';

// Slint has no grammar in the Shiki bundle of the docs site; an unknown fence language fails the
// build. QML is the closest bundled grammar (blocks of `name: value;`), so Slint is fenced as QML
// and titled "Slint".
export const PLATFORMS = {
  web: { title: 'Web', fence: 'tsx', kit: 'shadcn/ui, React' },
  android: { title: 'Android', fence: 'kotlin', kit: 'Jetpack Compose' },
  apple: { title: 'Apple', fence: 'swift', kit: 'SwiftUI' },
  desktop: { title: 'Desktop', fence: 'qml title="Slint"', kit: 'Slint' },
};

// The one place that says what has been run per platform (same wording as docs/content/ui-kit.md,
// "Verification", and docs/content/status.md).
export const VERIFICATION = {
  web: 'verified: typecheck, lint, unit and browser tests, a story per component.',
  android: '`core/ui` compiled and unit-tested on the authoring machine; never run on a device or emulator, no green CI run.',
  apple: 'written, not compiled.',
  desktop: 'written, not compiled.',
};

const EXAMPLE_SOURCE = {
  web: 'no story could be read',
  android: 'the file has no `@Preview` function',
  apple: 'the file has no `#Preview` block',
  desktop: 'the component is not used in the kit gallery',
};

const code = (v) => `\`${v}\``;
const list = (values) => (values?.length ? values.map(code).join(', ') : '-');
/** Prose made safe for MDX: `{`, `}`, `<` and `>` outside code spans are escaped. */
export const mdx = (text) => text.split(/(`[^`]*`)/).map((part, i) => (i % 2 ? part : part.replace(/[{}<>]/g, '\\$&'))).join('');
const cell = (text) => mdx(text).replace(/\|/g, '\\|');
const fenced = (lang, body) => {
  const fence = body.includes('```') ? '````' : '```';
  return `${fence}${lang}\n${body}\n${fence}`;
};
const frontMatter = (title, description) => `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---`;

/** The platform's conventional type name of a component (`AedstAlertDialog`; `AlertDialog` on web). */
const expectedName = (platform, name) => (platform === 'web' ? pascal(name) : `Aedst${pascal(name)}`);

/** Description: the web doc comment when present, else the first one found on another platform. */
export function describe(name, extracted) {
  for (const platform of Object.keys(PLATFORMS)) {
    const sentence = firstSentence(extracted[platform]?.doc ?? null);
    if (sentence) return sentence.replace(/\s+/g, ' ');
  }
  return `The \`${name}\` component of the AEDST UI kit on Web, Android, Apple and Desktop.`;
}

function platformSection(platform, name, c, sourcePath, x) {
  const entry = c[platform];
  const lines = [];
  if (entry.status === 'native') {
    lines.push(`**Status:** native. The platform SDK provides this and the kit adds no component: ${mdx(entry.note)}.`);
    return lines.join('\n\n');
  }
  lines.push(`**Status:** implemented (the file exists). **Verification:** ${VERIFICATION[platform]}`);
  lines.push(`**Source:** ${code(sourcePath)}`);
  for (const [axis, d] of Object.entries(c.deviations?.[platform] ?? {})) {
    lines.push(`**Deviation:** ${code(axis)} is ${list(d.values)} on ${PLATFORMS[platform].title}: ${mdx(d.reason.replace(/\.$/, ''))}.`);
  }
  if (x.api) lines.push('**Public API** (extracted from the source):', fenced(PLATFORMS[platform].fence, x.api));
  else lines.push('**Public API:** no signature could be extracted; read the source file.');
  if (platform === 'web' && Object.keys(x.axes ?? {}).length) {
    lines.push(`\`cva\` axes: ${Object.entries(x.axes).map(([axis, values]) => `${code(axis)} (${list(values)})`).join('; ')}.`);
  }
  if (x.example) {
    const label = x.example.kind === 'minimal'
      ? `**Usage** (minimal example built from the signature with the default variant; ${EXAMPLE_SOURCE[platform]}):`
      : `**Usage** (from ${x.example.from}):`;
    lines.push(label, fenced(PLATFORMS[platform].fence, x.example.code));
  }
  return lines.join('\n\n');
}

/**
 * Name of the component on a platform: the main export on web, the kit file's name on the native
 * kits (what the manifest records), or what the SDK provides for a `native` entry.
 */
export function platformName(platform, c, x) {
  const entry = c[platform];
  if (entry.status === 'native') return cell(entry.note);
  if (platform === 'web' && x?.main) return code(x.main);
  return code(entry.file.replace(/\.\w+$/, ''));
}

/** One component page. `sources`: { platform: repo path }; `extracted`: { platform: extraction result }. */
export function renderPage(name, c, sources, extracted) {
  const platforms = Object.keys(PLATFORMS);
  const axes = { variant: c.variants ?? [], size: c.sizes ?? [], ...(c.axes ?? {}) };
  const out = [frontMatter(name, describe(name, extracted)), HEADER, `# ${name}`];
  out.push(`Canonical name ${code(name)} (manifest: \`ui-kit.yaml\`). [All components](${ROUTE}) · [parity matrix](/ui-kit#component-parity-matrix).`);

  out.push('## Variants and sizes');
  const declared = Object.entries(axes).filter(([, values]) => values.length);
  if (declared.length) out.push(['| Axis | Canonical values (every platform) |', '|---|---|', ...declared.map(([axis, values]) => `| ${code(axis)} | ${list(values)} |`)].join('\n'));
  else out.push('No canonical variant or size axis.');

  out.push('## Platforms');
  out.push(['| Platform | Status | Name | Source |', '|---|---|---|---|',
    ...platforms.map((p) => `| ${PLATFORMS[p].title} (${PLATFORMS[p].kit}) | ${c[p].status} | ${platformName(p, c, extracted[p])} | ${sources[p] ? code(sources[p]) : '-'} |`)].join('\n'));
  const notes = [];
  for (const p of platforms) {
    const own = c[p].status === 'implemented' && p !== 'web' ? c[p].file.replace(/\.\w+$/, '') : null;
    if (own && normalise(own) !== normalise(expectedName(p, name))) {
      notes.push(`- On ${PLATFORMS[p].title} ${code(name)} is named ${code(own)}.`);
    }
    if (c[p].status === 'native') notes.push(`- On ${PLATFORMS[p].title} ${code(name)} is native: ${mdx(c[p].note)}.`);
    for (const [axis, d] of Object.entries(c.deviations?.[p] ?? {})) {
      notes.push(`- ${PLATFORMS[p].title} deviates on ${code(axis)}: ${list(d.values)}. Reason: ${mdx(d.reason.replace(/\.$/, ''))}.`);
    }
  }
  if (notes.length) out.push(notes.join('\n'));

  out.push(`<Tabs items={${JSON.stringify(platforms.map((p) => PLATFORMS[p].title))}}>`);
  for (const p of platforms) out.push(`<Tab value="${PLATFORMS[p].title}">`, platformSection(p, name, c, sources[p], extracted[p] ?? {}), '</Tab>');
  out.push('</Tabs>');
  return `${out.join('\n\n')}\n`;
}

/** Page of an alias entry (one name served by another entry). `names`: the target's name per platform. */
export function renderAlias(name, target, names) {
  const platforms = Object.keys(PLATFORMS);
  return `${[
    frontMatter(name, `\`${name}\` is an alias of \`${target}\`: the same component serves both names on every platform.`),
    HEADER,
    `# ${name}`,
    `${code(name)} is an alias of [${code(target)}](${ROUTE}/${target}) in \`ui-kit.yaml\`: no platform has a separate ${code(name)} component. Use the ${code(target)} component.`,
    ['| Platform | Use |', '|---|---|', ...platforms.map((p) => `| ${PLATFORMS[p].title} | ${names[p]} |`)].join('\n'),
    `[All components](${ROUTE}) · [parity matrix](/ui-kit#component-parity-matrix).`,
  ].join('\n\n')}\n`;
}

/** The index page: every component with its name on each platform. `rows`: [{ name, alias, names }]. */
export function renderIndex(rows) {
  const platforms = Object.keys(PLATFORMS);
  return `${[
    frontMatter('Component reference', 'One page per UI kit component: status, source file, public API and a usage example on Web, Android, Apple and Desktop.'),
    HEADER,
    '# Component reference',
    `One page per entry of \`ui-kit.yaml\` (${rows.length} entries). Each page lists the canonical variants and sizes and, per platform, the status, the source file, the public API extracted from that file and a usage example taken from the source (a story, a preview or the kit gallery) where one exists. The pages are generated: run \`task docs:ui-kit\` after changing a component or the manifest. The cross-platform rules and the parity matrix are on the [UI kit page](/ui-kit).`,
    `What has been run per platform: ${platforms.map((p) => `**${PLATFORMS[p].title}** ${VERIFICATION[p].replace(/\.$/, '')}`).join('; ')}. Details: [platform status](/status).`,
    'Platform names differ from the canonical name in places; search this table for either.',
    ['| Component | ' + platforms.map((p) => PLATFORMS[p].title).join(' | ') + ' |', `|---|${platforms.map(() => '---').join('|')}|`,
      ...rows.map((r) => `| [${code(r.name)}](${ROUTE}/${r.name})${r.alias ? ` (alias of ${code(r.alias)})` : ''} | ${platforms.map((p) => r.names[p]).join(' | ')} |`)].join('\n'),
  ].join('\n\n')}\n`;
}
