#!/usr/bin/env bash
# Checks file/resource naming conventions that per-platform linters don't cover
# (file names, directories) — see /CONVENTIONS.md for the full standard.
#
# Usage:
#   ./scripts/check-naming.sh            # check all tracked files
#   ./scripts/check-naming.sh --staged   # check only staged files (pre-commit)
#   ./scripts/check-naming.sh --stdin    # check the paths on stdin (used by apps/web `pnpm check:selftest`)
set -euo pipefail

fail=0
warn() { echo "WARNING: $*"; }
err()  { echo "ERROR: $*"; fail=1; }

if [[ "${1:-}" == "--staged" ]]; then
  files=$(git diff --cached --name-only --diff-filter=ACMR)
elif [[ "${1:-}" == "--stdin" ]]; then
  files=$(cat)
else
  files=$(git ls-files)
fi

kebab='^[a-z0-9]+(-[a-z0-9]+)*$'
pascal='^[A-Z][a-zA-Z0-9]*$'
snake='^[a-z0-9]+(_[a-z0-9]+)*$'

while IFS= read -r f; do
  [[ -z "$f" ]] && continue
  [[ -f "$f" ]] || continue  # skip files deleted-but-not-yet-committed
  base=$(basename -- "$f")
  name="${base%.*}"
  name="${name%.d}" # `foo.d.ts` declaration files: the stem is `foo`
  case "$f" in apps/web/*) name="${name%.test}"; name="${name%.spec}"; name="${name%.contract}" ;; esac # `foo.contract.test.ts`: the stem is `foo`

  case "$f" in
    # --- Generated code: naming is owned by the generator, not us ---
    apps/server/gen/*)
      ;;

    # --- Web (apps/web: shared, app, admin, landing) ---
    apps/web/*/src/app/*/page.tsx|apps/web/*/src/app/*/layout.tsx|apps/web/*/src/app/*/loading.tsx|apps/web/*/src/app/*/error.tsx|apps/web/*/src/app/*/not-found.tsx|apps/web/*/src/app/*/route.ts|apps/web/*/src/app/*/global-error.tsx)
      ;; # Next.js framework-mandated literal file names
    apps/web/admin/src/app/routeTree.gen.ts)
      ;; # generated by the TanStack Router plugin
    apps/web/admin/src/main.tsx|apps/web/admin/src/app/router.tsx|apps/web/admin/src/app/router.test.tsx|apps/web/admin/src/app/i18n/navigation.tsx)
      ;; # Vite entry and router wiring (the navigation module mirrors next-intl's API, it is not a component)
    apps/web/admin/src/app/routes/*)
      # TanStack Router file-based routes: the path is the URL, so segments are
      # lowercase kebab-case plus the router's markers (__root, $param, _pathless).
      stem="${base%%.*}"
      seg_re='^(__root|\$[a-z][a-zA-Z0-9]*|_?[a-z0-9]+(-[a-z0-9]+)*)$'
      [[ "$stem" =~ $seg_re ]] || err "$f: route file must be kebab-case, __root, \$param or _pathless (TanStack Router)"
      rel="${f#apps/web/admin/src/app/routes/}"
      while [[ "$rel" == */* ]]; do
        seg="${rel%%/*}"; rel="${rel#*/}"
        [[ "$seg" =~ $seg_re ]] || err "$f: route directory '$seg' must be kebab-case, \$param or _pathless (TanStack Router)"
      done
      ;;
    apps/web/shared/*.tsx|apps/web/app/src/*.tsx|apps/web/admin/src/*.tsx|apps/web/landing/src/*.tsx|apps/web/shared/*.ts|apps/web/app/src/*.ts|apps/web/admin/src/*.ts|apps/web/landing/src/*.ts)
      # Every web source file is kebab-case, React components included (owner decision
      # 2026-11-21): task-list.tsx exports TaskList. Framework names (page, layout,
      # opengraph-image, ...) are kebab-case already, so they need no exception here.
      stem="${base%%.*}" # foo.test.tsx, foo.stories.tsx, foo.browser.test.ts, foo.d.ts: the stem is `foo`
      [[ "$stem" =~ $kebab ]] || err "$f: web source file must be kebab-case (task-list.tsx exports TaskList); framework files keep their framework names"
      ;;

    # --- Server (apps/server, Go) ---
    apps/server/*.go)
      [[ "$name" =~ $snake ]] || err "$f: Go file must be snake_case.go (or one lowercase word)"
      ;;

    # --- Android (apps/android, Kotlin) ---
    apps/android/*.kt)
      [[ "$name" =~ $pascal ]] || err "$f: Kotlin file must be PascalCase.kt"
      ;;
    apps/android/*/res/*.xml)
      [[ "$name" =~ $snake ]] || err "$f: Android resource must be snake_case"
      ;;

    # --- Apple (apps/apple, Swift) ---
    apps/apple/*.swift)
      [[ "$name" =~ ^[A-Z][a-zA-Z0-9]*(\+[A-Z][a-zA-Z0-9]*)?$ ]] || err "$f: Swift file must be PascalCase.swift (Type+Extension.swift allowed)"
      ;;

    # --- Gateway (apps/gateway, Rust) ---
    apps/gateway/*.rs)
      [[ "$name" =~ $snake ]] || err "$f: Rust files must be snake_case (rustfmt convention, see CONVENTIONS.md)"
      ;;

    # --- Desktop (apps/desktop, Rust + Slint) ---
    apps/desktop/*.rs|apps/desktop/*.slint)
      [[ "$name" =~ $snake ]] || err "$f: Rust and Slint files must be snake_case (rustfmt convention, see CONVENTIONS.md)"
      ;;
  esac
done <<< "$files"

if [[ $fail -ne 0 ]]; then
  echo ""
  echo "Naming check failed. See CONVENTIONS.md for the standard." >&2
  exit 1
fi
echo "Naming check passed."
