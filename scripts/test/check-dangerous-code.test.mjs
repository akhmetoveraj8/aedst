// Negative self-test of scripts/check-dangerous-code.mjs: every rule must fire on its bad sample,
// stay silent on its safe sample, honour only a waiver that names it, and see patterns that a
// one-line scanner misses. Run: `node --test scripts/test`.
import assert from "node:assert/strict";
import { test } from "node:test";
import { findWaivers, isProtectedGateFile, isScannable, scanText } from "../check-dangerous-code.mjs";
import { RULES } from "../dangerous-code/rules.mjs";

const BAD = {
  "js-eval": ["a.ts", "const x = eval(input);"],
  "js-shell-exec": ["a.ts", "exec(`rm ${dir}`);"],
  "js-shell-true": ["a.mjs", "spawn(cmd, args, { shell: true });"],
  "go-shell-exec": ["a.go", 'exec.Command("sh", "-c", cmd)'],
  "py-shell": ["a.py", "os.system(cmd)"],
  "web-inner-html": ["a.ts", "el.innerHTML = value;"],
  "react-dangerous-html": ["a.tsx", "<div dangerouslySetInnerHTML={{ __html: v }} />"],
  "go-template-unescaped": ["a.go", "out := template.HTML(userInput)"],
  "go-sql-concat": ["a.go", 'q := fmt.Sprintf("SELECT * FROM t WHERE id = %s", id)'],
  "js-sql-template": ["a.ts", "db.query(`SELECT * FROM t WHERE id = ${id}`);"],
  "tls-verify-off": ["a.go", "&tls.Config{InsecureSkipVerify: true}"],
  "android-trust-all": ["a.kt", "settings.setJavaScriptEnabled(true)"],
  "apple-ats-off": ["a.swift", "NSAllowsArbitraryLoads"],
  "weak-hash": ["a.ts", "createHash('md5')"],
  "insecure-random": ["a.ts", "const sessionId = Math.random().toString(36);"],
  "jwt-unsafe": ["a.ts", "const claims = jwtDecode(token);"],
  "secret-literal": ["a.go", 'key := "AKIAABCDEFGHIJKLMNOP"'],
  "secret-assign": ["a.ts", 'const apiKey = "Zk3pQ9vL2mXw8RtY";'],
  "web-token-storage": ["a.ts", "localStorage.setItem('access_token', t);"],
  "cookie-flags-off": ["a.ts", "{ httpOnly: false }"],
  "cors-wildcard-credentials": ["a.ts", "res.setHeader('Access-Control-Allow-Origin', '*');"],
  "go-default-client": ["a.go", "resp, err := http.Get(url)"],
  "bind-all-interfaces": ["a.go", 'http.ListenAndServe("0.0.0.0:8080", h)'],
  "rust-unsafe": ["a.rs", "unsafe { ptr.read() }"],
  "ts-ignore": ["a.ts", "// @ts-ignore"],
};

const SAFE = [
  ["a.ts", "const m = /^(\\S+)\\s+(\\d+)$/.exec(line);"],
  ["a.ts", "execFile('git', ['status']);"],
  ["a.ts", "const id = crypto.randomUUID();"],
  ["a.go", "q := queries.GetTask(ctx, id)"],
  ["a.ts", "const label = 'access_token';"],
  ["a.ts", "const result = evaluate(input);"],
  ["a.ts", "setTimeout(() => run(), 10);"],
  ["a.ts", "const token = readCookie();\nconst n = 1;\nconst r = Math.random();"],
];

const ids = (file, text) => scanText(file, text).map((h) => h.rule.id);

test("every rule has a bad sample", () => {
  const missing = RULES.filter((r) => !(r.id in BAD)).map((r) => r.id);
  assert.deepEqual(missing, [], "add a BAD sample for each new rule");
});

for (const [id, [file, line]] of Object.entries(BAD)) {
  test(`rule ${id} fires`, () => {
    assert.ok(ids(file, line).includes(id), `${id} did not fire on: ${line}`);
  });
  test(`rule ${id} accepts a waiver that names it`, () => {
    assert.deepEqual(scanText(file, `${line} // security-ignore: ${id} -- reviewed, constant input only`), []);
  });
  test(`rule ${id} ignores a waiver for another rule`, () => {
    const other = id === "js-eval" ? "weak-hash" : "js-eval";
    assert.ok(ids(file, `${line} // security-ignore: ${other} -- reviewed, constant input only`).includes(id));
  });
}

test("safe code is not flagged", () => {
  for (const [file, text] of SAFE) assert.deepEqual(scanText(file, text), [], text);
});

test("a waiver without a rule id or a real reason does not count", () => {
  for (const w of ["security-ignore:", "security-ignore: reviewed", "security-ignore: js-eval", "security-ignore: js-eval -- ok"]) {
    assert.ok(ids("a.ts", `eval(x); // ${w}`).includes("js-eval"), w);
  }
});

test("a GENERATED marker in the text does not disable the scan", () => {
  assert.ok(ids("apps/web/app/src/a.ts", "// GENERATED - do not edit\nconst v = eval(input);").includes("js-eval"));
  assert.ok(ids("a.go", "// Code generated by hand. DO NOT EDIT.\nresp, err := http.Get(url)").includes("go-default-client"));
});

test("patterns split across lines are found", () => {
  assert.ok(ids("a.ts", "const v = eval\n  (input);").includes("js-eval"));
  assert.ok(ids("a.go", 'cmd := exec.Command(\n\t"sh",\n\t"-c",\n\tuser)').includes("go-shell-exec"));
  const hit = scanText("a.ts", "const a = 1;\nconst v = eval\n(input);").find((h) => h.rule.id === "js-eval");
  assert.equal(hit?.line, 2);
});

test("aliases of eval are found", () => {
  for (const src of ["const e = eval;", "const run = globalThis.eval;", "(0, eval)(code);", "window['eval'](code);", "Function('return ' + body)();", "setTimeout('doWork()', 10);"]) {
    assert.ok(ids("a.ts", src).includes("js-eval"), src);
  }
});

test("biome security suppressions map to the matching rule only", () => {
  const html = '// biome-ignore lint/security/noDangerouslySetInnerHtml: serialized JSON with `<` escaped\n<script dangerouslySetInnerHTML={{ __html: json }} />';
  assert.deepEqual(scanText("a.tsx", html), []);
  const wrong = "// biome-ignore lint/security/noDangerouslySetInnerHtml: serialized JSON with `<` escaped\nconst v = eval(input);";
  assert.ok(ids("a.tsx", wrong).includes("js-eval"));
});

test("findWaivers parses rule ids and reasons", () => {
  const [w] = findWaivers("x(); // security-ignore: js-eval, weak-hash -- constant input from the build");
  assert.deepEqual(w.ids, ["js-eval", "weak-hash"]);
  assert.equal(w.reason, "constant input from the build");
});

test("tests, generated and docs paths are not scanned; generated code is recognised by path", () => {
  assert.equal(isScannable("apps/web/app/src/a.test.ts"), false);
  assert.equal(isScannable("apps/server/gen/x.go"), false);
  assert.equal(isScannable("apps/server/internal/x/db/query.sql.go"), false);
  assert.equal(isScannable("docs/content/engineering/ai-safe-code.md"), false);
  assert.equal(isScannable("apps/web/app/src/a.ts"), true);
});

test("gate files are protected", () => {
  for (const f of [".claude/settings.json", ".claude/hooks/stop-gate.sh", "scripts/check-dangerous-code.mjs", "scripts/dangerous-code/rules.mjs", "lefthook.yml", ".semgrep/aedst.yml"]) {
    assert.ok(isProtectedGateFile(f), f);
  }
  assert.equal(isProtectedGateFile("apps/web/app/src/a.ts"), false);
});
