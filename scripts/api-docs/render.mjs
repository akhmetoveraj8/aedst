// Renders one Markdown page per API module from parsed protos.
import { flattenMessages } from "./parse-proto.mjs";
import { camel, makeSampler } from "./samples.mjs";

export const TITLES = {
  admin: "Admin",
  appattest: "App Attest",
  capabilities: "Capabilities",
  events: "Event ingest",
  integrity: "Play Integrity",
  media: "Media",
  notifications: "Notifications",
  search: "Search",
  tasks: "Tasks",
};

const cell = (s) => String(s ?? "").replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim() || "—";
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]/g, "");
const firstSentence = (doc) => {
  const flat = (doc ?? "").replace(/\s*\n\s*/g, " ").trim();
  const m = flat.match(/^(.+?[.!?])(\s|$)/);
  return m ? m[1] : flat;
};

const PHRASES = {
  min_len: (v) => `min length ${v}`,
  max_len: (v) => `max length ${v}`,
  len: (v) => `length ${v}`,
  min_items: (v) => `min ${v} items`,
  max_items: (v) => `max ${v} items`,
  min_bytes: (v) => `min ${v} bytes`,
  max_bytes: (v) => `max ${v} bytes`,
  gte: (v) => `≥ ${v}`, lte: (v) => `≤ ${v}`, gt: (v) => `> ${v}`, lt: (v) => `< ${v}`,
  pattern: (v) => `pattern ${v}`,
  defined_only: () => "known value",
  not_in: (v) => (v.trim() === "[0]" ? "not UNSPECIFIED" : `not in ${v}`),
  in: (v) => `one of ${v}`,
  uuid: () => "UUID", email: () => "email", uri: () => "URI", required: () => "required", unique: () => "unique",
};

export function constraints(options) {
  if (!options) return "";
  const each = /\bitems\b/.test(options);
  const parts = [];
  const re = /\b(min_len|max_len|len|min_items|max_items|min_bytes|max_bytes|gte|lte|gt|lt|pattern|defined_only|not_in|in|uuid|email|uri|required|unique)\b\s*[:=]\s*(\[[^\]]*\]|"(?:[^"\\]|\\.)*"|[\w.+-]+)/g;
  for (const m of options.matchAll(re)) {
    if (m[2] === "false") continue;
    parts.push(PHRASES[m[1]](m[2].replace(/^"|"$/g, "")));
  }
  if (!parts.length) return "";
  return (each ? "each: " : "") + parts.join(", ");
}

export function renderModule(module, files, repoPath) {
  const index = new Map();
  const messages = [];
  const enums = [];
  const services = [];
  for (const f of files) {
    for (const m of flattenMessages(f.messages)) { index.set(m.name, { kind: "message", def: m }); messages.push(m); }
    for (const m of flattenMessages(f.messages)) for (const e of m.enums) { enums.push(e); index.set(e.name, { kind: "enum", def: e }); }
    for (const e of f.enums) { enums.push(e); index.set(e.name, { kind: "enum", def: e }); }
    for (const s of f.services) services.push({ ...s, pkg: f.package });
  }
  const { sampleMessage } = makeSampler(index);
  const inline = new Set(services.flatMap((s) => s.rpcs.flatMap((r) => [r.request, r.response])));

  const typeCell = (f) => {
    const link = (t) => (index.has(t) || index.has(t.split(".").pop()) ? `[${t}](#${slug(t)})` : `\`${t}\``);
    const map = f.type.match(/^map<\s*(\w+),\s*([\w.]+)>$/);
    const base = map ? `map<${map[1]}, ${link(map[2])}>` : link(f.type);
    return `${f.label === "repeated" ? "list of " : ""}${base}${f.label === "optional" ? " (optional)" : ""}${f.oneof ? ` (oneof ${f.oneof})` : ""}`;
  };

  const fieldTable = (msg) => {
    if (!msg.fields.length) return "_No fields._\n";
    const rows = msg.fields.map((f) => `| \`${f.name}\` | ${cell(typeCell(f))} | ${cell(constraints(f.options))} | ${cell(f.doc)} |`);
    return ["| Field | Type | Constraints | Description |", "|---|---|---|---|", ...rows, ""].join("\n");
  };

  const json = (o) => JSON.stringify(o, null, 2);
  const L = [];
  const first = services[0];
  const pkg = first?.pkg ?? "";
  L.push("---", `title: "${TITLES[module] ?? module} API"`,
    `description: ${JSON.stringify(firstSentence(first?.doc) || `Reference for ${pkg}.`)}`, "---", "",
    `{/* GENERATED by \`task docs:api\` from ${repoPath}. Do not edit by hand: change the .proto comments and regenerate. */}`, "",
    `# ${TITLES[module] ?? module} API`, "",
    `Package \`${pkg}\` · source \`${repoPath}\` · conventions, authentication and errors: [API overview](/api).`, "");

  for (const s of services) {
    L.push(`## ${s.name}`, "", s.doc, "",
      "| RPC | Path | Summary |", "|---|---|---|",
      ...s.rpcs.map((r) => `| [${r.name}](#${slug(r.name)}) | \`/${s.pkg}.${s.name}/${r.name}\` | ${cell(firstSentence(r.doc))} |`), "");
    for (const r of s.rpcs) {
      const req = index.get(r.request)?.def;
      const res = index.get(r.response)?.def;
      const skip = new Set(["page_token"]);
      L.push(`### ${r.name}`, "", r.doc || "", "");
      if (r.serverStream || r.clientStream) L.push("> Streaming RPC.", "");
      if (req) L.push(`**Request** \`${req.name}\``, "", fieldTable(req));
      if (res) L.push(`**Response** \`${res.name}\``, "", fieldTable(res));
      L.push("Example:", "", "```bash",
        `curl -sS "$AEDST_URL/${s.pkg}.${s.name}/${r.name}" \\`,
        `  -H "Authorization: Bearer $TOKEN" \\`, `  -H "Content-Type: application/json" \\`,
        `  -H "Connect-Protocol-Version: 1" \\`, `  -d '${req ? json(sampleMessage(req, 0, skip)).replace(/'/g, "'\\''") : "{}"}'`,
        "```", "", "Response (`200`):", "", "```json", res ? json(sampleMessage(res, 0)) : "{}", "```", "");
    }
  }

  const types = messages.filter((m) => !inline.has(m.name));
  if (types.length || enums.length) {
    L.push("## Types", "");
    for (const m of types) L.push(`### ${m.name}`, "", m.doc || "", "", fieldTable(m));
    for (const e of enums) {
      L.push(`### ${e.name}`, "", e.doc || "", "", "| Value | Number | Description |", "|---|---|---|",
        ...e.values.map((v) => `| \`${v.name}\` | ${v.number} | ${cell(v.doc)} |`), "");
    }
  }
  return `${L.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

export { camel };
