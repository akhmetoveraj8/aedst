// Renders one Markdown page per proto package from the descriptor model (descriptor.mjs).
import { flattenMessages } from "./descriptor.mjs";
import { camel, makeSampler } from "./samples.mjs";

export const TITLES = {
  admin: "Admin",
  appattest: "App Attest",
  capabilities: "Capabilities",
  events: "Event ingest",
  integrity: "Play Integrity",
  media: "Media",
  notifications: "Notifications",
  search: "Search",
  tasks: "Tasks",
  webhooks: "Webhooks",
};

const cell = (s) => String(s ?? "").replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim() || "—";
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]/g, "");
const firstSentence = (doc) => {
  const flat = (doc ?? "").replace(/\s*\n\s*/g, " ").trim();
  const m = flat.match(/^(.+?[.!?])(\s|$)/);
  return m ? m[1] : flat;
};

// Protovalidate rule name (protojson lowerCamelCase) -> phrase. The order here is the output order.
const PHRASES = {
  required: () => "required",
  uuid: () => "UUID", email: () => "email", uri: () => "URI",
  len: (v) => `length ${v}`,
  minLen: (v) => `min length ${v}`,
  maxLen: (v) => `max length ${v}`,
  minBytes: (v) => `min ${v} bytes`,
  maxBytes: (v) => `max ${v} bytes`,
  minItems: (v) => `min ${v} items`,
  maxItems: (v) => `max ${v} items`,
  unique: () => "unique",
  gt: (v) => `> ${v}`, gte: (v) => `≥ ${v}`, lt: (v) => `< ${v}`, lte: (v) => `≤ ${v}`,
  pattern: (v) => `pattern ${v}`,
  definedOnly: () => "known value",
  in: (v) => `one of ${JSON.stringify(v)}`,
  notIn: (v) => (Array.isArray(v) && v.length === 1 && v[0] === 0 ? "not UNSPECIFIED" : `not in ${JSON.stringify(v)}`),
};

// Humanises a field's `(buf.validate.field)` rules as buf prints them in the descriptor JSON.
export function constraints(rules) {
  if (!rules) return "";
  const found = new Map();
  let each = false;
  const walk = (node, underItems) => {
    for (const [key, value] of Object.entries(node)) {
      if (value === false) continue;
      if (key in PHRASES) {
        found.set(key, value);
        each ||= underItems;
      } else if (value && typeof value === "object" && !Array.isArray(value)) {
        walk(value, underItems || key === "items");
      }
    }
  };
  walk(rules, false);
  const parts = Object.keys(PHRASES).filter((k) => found.has(k)).map((k) => PHRASES[k](found.get(k)));
  if (!parts.length) return "";
  return (each ? "each: " : "") + parts.join(", ");
}

export function renderModule(module, files, repoPath, links = { overview: "/api", openapi: "" }, kind = "API") {
  const index = new Map();
  const messages = [];
  const enums = [];
  const services = [];
  for (const f of files) {
    for (const m of flattenMessages(f.messages)) { index.set(m.name, { kind: "message", def: m }); messages.push(m); }
    for (const m of flattenMessages(f.messages)) for (const e of m.enums) { enums.push(e); index.set(e.name, { kind: "enum", def: e }); }
    for (const e of f.enums) { enums.push(e); index.set(e.name, { kind: "enum", def: e }); }
    for (const s of f.services) services.push({ ...s, pkg: f.package });
  }
  const { sampleMessage } = makeSampler(index);
  const inline = new Set(services.flatMap((s) => s.rpcs.flatMap((r) => [r.request, r.response])));

  const typeCell = (f) => {
    const link = (t) => (index.has(t) || index.has(t.split(".").pop()) ? `[${t}](#${slug(t)})` : `\`${t}\``);
    const map = f.type.match(/^map<\s*(\w+),\s*([\w.]+)>$/);
    const base = map ? `map<${map[1]}, ${link(map[2])}>` : link(f.type);
    return `${f.label === "repeated" ? "list of " : ""}${base}${f.label === "optional" ? " (optional)" : ""}${f.oneof ? ` (oneof ${f.oneof})` : ""}`;
  };

  const fieldTable = (msg) => {
    if (!msg.fields.length) return "_No fields._\n";
    const rows = msg.fields.map((f) => `| \`${f.name}\` | ${cell(typeCell(f))} | ${cell(constraints(f.rules))} | ${cell(f.doc)} |`);
    return ["| Field | Type | Constraints | Description |", "|---|---|---|---|", ...rows, ""].join("\n");
  };

  const json = (o) => JSON.stringify(o, null, 2);
  const L = [];
  const first = services[0];
  const pkg = first?.pkg ?? files[0]?.package ?? "";
  const pkgDoc = kind === "events" ? `Payloads of the integration events the ${module} module publishes, as Protobuf messages serialised as JSON with the proto field names.` : "";
  L.push("---", `title: "${TITLES[module] ?? module} ${kind}"`,
    `description: ${JSON.stringify(firstSentence(first?.doc) || pkgDoc || `Reference for ${pkg}.`)}`, "---", "",
    `{/* GENERATED by \`task docs:api\` from ${repoPath}. Do not edit by hand: change the .proto comments and regenerate. */}`, "",
    `# ${TITLES[module] ?? module} ${kind}`, "",
    `Package \`${pkg}\` · source \`${repoPath}\` · ${kind === "events" ? "delivery, ordering and evolution rules: [events]" : "conventions, authentication and errors: [API overview]"}(${links.overview}).`, "");
  if (pkgDoc) L.push(pkgDoc, "");
  const tryIt = links.interactive ? ` Try the calls on the [interactive OpenAPI page](${links.interactive}).` : "";
  if (links.openapi) L.push(`Machine-readable contract: [OpenAPI 3.1 (YAML)](${links.openapi}), generated from the same \`.proto\` files.${tryIt}`, "");

  for (const s of services) {
    L.push(`## ${s.name}`, "", s.doc, "",
      "| RPC | Path | Summary |", "|---|---|---|",
      ...s.rpcs.map((r) => `| [${r.name}](#${slug(r.name)}) | \`/${s.pkg}.${s.name}/${r.name}\` | ${cell(firstSentence(r.doc))} |`), "");
    for (const r of s.rpcs) {
      const req = index.get(r.request)?.def;
      const res = index.get(r.response)?.def;
      const skip = new Set(["page_token"]);
      L.push(`### ${r.name}`, "", r.doc || "", "");
      if (r.serverStream || r.clientStream) L.push("> Streaming RPC.", "");
      if (r.noSideEffects) L.push("> No side effects: also callable as a Connect `GET`, see [conditional reads](/engineering/api-design#conditional-reads-and-caching).", "");
      if (req) L.push(`**Request** \`${req.name}\``, "", fieldTable(req));
      if (res) L.push(`**Response** \`${res.name}\``, "", fieldTable(res));
      L.push("Example:", "", "```bash",
        `curl -sS "$AEDST_URL/${s.pkg}.${s.name}/${r.name}" \\`,
        `  -H "Authorization: Bearer $TOKEN" \\`, `  -H "Content-Type: application/json" \\`,
        `  -H "Connect-Protocol-Version: 1" \\`, `  -d '${req ? json(sampleMessage(req, 0, skip)).replace(/'/g, "'\\''") : "{}"}'`,
        "```", "", "Response (`200`):", "", "```json", res ? json(sampleMessage(res, 0)) : "{}", "```", "");
    }
  }

  const types = messages.filter((m) => !inline.has(m.name));
  if (types.length || enums.length) {
    L.push("## Types", "");
    for (const m of types) L.push(`### ${m.name}`, "", m.doc || "", "", fieldTable(m));
    for (const e of enums) {
      L.push(`### ${e.name}`, "", e.doc || "", "", "| Value | Number | Description |", "|---|---|---|",
        ...e.values.map((v) => `| \`${v.name}\` | ${v.number} | ${cell(v.doc)} |`), "");
    }
  }
  return `${L.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

export { camel };
