#!/usr/bin/env node
// Generates the measured numbers of docs/content/status.md from the working tree, so they cannot drift.
//   node scripts/status-metrics.mjs          rewrite the block between the metrics markers
//   node scripts/status-metrics.mjs --check  fail when the block is stale (CI)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const statusPath = join(root, "docs", "content", "status.md");
const START = "<!-- metrics:start (generated by scripts/status-metrics.mjs; do not edit) -->";
const END = "<!-- metrics:end -->";

function fileSizeTable() {
  const out = execFileSync("bash", ["scripts/check-file-size.sh", "--summary"], {
    cwd: root,
    encoding: "utf8",
  });
  const rows = out
    .split("\n")
    .map((line) => line.trim().split(/\s+/))
    .filter((cols) => cols.length === 5 && /^\d+$/.test(cols[1]));
  const lines = [
    "| Platform | Files | Yellow (301-400) | Orange (401-500) | Red (over 500) |",
    "|---|---|---|---|---|",
    ...rows.map((c) => `| ${c[0]} | ${c[1]} | ${c[2]} | ${c[3]} | ${c[4]} |`),
  ];
  return lines.join("\n");
}

const block = `${START}\n\nFile-size policy counts (\`task check:file-size\`, hand-written source only):\n\n${fileSizeTable()}\n\n${END}`;
const text = readFileSync(statusPath, "utf8");
const pattern = {
  test: (t) => t.includes(START) && t.includes(END),
};
if (!pattern.test(text)) {
  console.error(`status.md has no metrics markers (${START} ... ${END})`);
  process.exit(2);
}
const from = text.indexOf(START);
const to = text.indexOf(END) + END.length;
const next = text.slice(0, from) + block + text.slice(to);
if (process.argv.includes("--check")) {
  if (next !== text) {
    console.error("docs/content/status.md metrics are stale: run `node scripts/status-metrics.mjs`");
    process.exit(1);
  }
  console.log("OK: status metrics are current");
} else if (next !== text) {
  writeFileSync(statusPath, next);
  console.log("status.md metrics updated");
} else {
  console.log("status.md metrics already current");
}
