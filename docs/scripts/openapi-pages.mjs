#!/usr/bin/env node
// Generates the interactive OpenAPI pages: one per docs/public/openapi/aedst.<module>.v1.yaml,
// with fumadocs-openapi's own file generator. Output (never edit by hand):
//   docs/content/modules/<module>/openapi.mdx   module packages
//   docs/content/api/<package>-openapi.mdx      platform packages (scripts/api-docs PLATFORM_PACKAGES)
// and the page is listed in the folder's meta.json right after the reference page.
// Usage (any working directory):
//   node docs/scripts/openapi-pages.mjs           write the pages
//   node docs/scripts/openapi-pages.mjs --check   exit 1 when a page or meta.json entry is stale or missing
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateFilesOnly } from "fumadocs-openapi";
import { openapiPagePath, pagePath, routeOf } from "../../scripts/api-docs/index.mjs";

const docsDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(docsDir, "..");
// src/lib/openapi.ts lists public/openapi relative to docs/, exactly as `next build` does.
process.chdir(docsDir);
const { openapi } = await import("../src/lib/openapi.ts");

const moduleOf = (id) => id.split(".")[1];
const stem = (path) => basename(path).replace(/\.mdx?$/, "");

const files = await generateFilesOnly({
  input: openapi,
  per: "file",
  // Path relative to docs/content, without the extension.
  name: (entry) => openapiPagePath(moduleOf(entry.schemaId)).replace(/^docs\/content\//, "").replace(/\.mdx$/, ""),
  // Short single-line values: scripts/check-docs.mjs and src/lib/content.ts read flat `key: value` front matter.
  frontmatter: (title) => {
    const id = title.match(/\(([\w.]+)\)/)?.[1] ?? title;
    return { title: `${id} OpenAPI`, description: `Interactive OpenAPI 3.1 page for ${id}.` };
  },
  addGeneratedComment: "GENERATED by docs/scripts/openapi-pages.mjs from docs/public/openapi. Do not edit by hand.",
});

// repo-relative path -> wanted text
const wanted = new Map();
for (const id of Object.keys(openapi.options.input).sort()) {
  const module = moduleOf(id);
  const page = openapiPagePath(module);
  const file = files.find((f) => `docs/content/${f.path.replaceAll("\\", "/")}` === page);
  if (!file) throw new Error(`no page generated for ${id}`);
  const intro = `Requests go to \`http://localhost:8080\` unless you pick another server. Reference: [${id}](${routeOf(pagePath(module))}) · plain contract: [OpenAPI 3.1 (YAML)](/openapi/${id}.yaml).`;
  wanted.set(page, `${file.content}\n\n${intro}\n`);

  // meta.json: list the page right after the reference page. A folder without meta.json lists it by itself.
  const metaPath = `${dirname(page)}/meta.json`;
  if (!wanted.has(metaPath) && !existsSync(join(root, metaPath))) continue;
  const meta = JSON.parse(wanted.get(metaPath) ?? readFileSync(join(root, metaPath), "utf8"));
  if (Array.isArray(meta.pages) && !meta.pages.includes(stem(page))) {
    const after = meta.pages.indexOf(stem(pagePath(module)));
    meta.pages.splice(after < 0 ? meta.pages.length : after + 1, 0, stem(page));
    wanted.set(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
  }
}

const check = process.argv.includes("--check");
const stale = [];
for (const [name, text] of wanted) {
  const path = join(root, name);
  const current = existsSync(path) ? readFileSync(path, "utf8").replaceAll("\r\n", "\n") : null;
  if (current === text) continue;
  stale.push(name);
  if (!check) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
if (check && stale.length) {
  console.error(`stale OpenAPI pages: ${stale.join(", ")} (run: node docs/scripts/openapi-pages.mjs)`);
  process.exit(1);
}
console.log(`${files.length} OpenAPI pages ${check ? "up to date" : `written (${stale.length} changed)`}`);
